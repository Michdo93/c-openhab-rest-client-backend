"""Generates src/calls.c and methods.json from python-openhab-rest-client.

    python3 tools/gen_calls.py <c-openhab-rest-client>/tools/py2c.py \
        <python-openhab-rest-client>/openhab src/calls.c methods.json

calls.c maps "Class.method" plus a JSON object with named arguments to the function of
c-openhab-rest-client (openhab_call for REST calls, openhab_open_stream for event streams).
methods.json lists every function with its parameters for the test app.
"""
import importlib.util
import json
import sys

spec = importlib.util.spec_from_file_location("py2c", sys.argv[1])
py2c = importlib.util.module_from_spec(spec)
spec.loader.exec_module(py2c)

CONV = {"str": "s_", "bool": "b_", "int": "i_", "float": "d_", "json": "j_"}
OPTCONV = {"str": "s_", "bool": "f_", "int": "i_", "float": "d_", "json": "j_"}


def call_expr(m):
    req = [f'{CONV[t]}(a_(args, "{n}"))' for n, t, d, r in m.params if r]
    if m.optional:
        fields = [f'.{n} = {OPTCONV[t]}(a_(args, "{n}"))' for n, t, d, r in m.params if not r]
        return f"{m.cname}_({', '.join(['c'] + req)}, ({m.cname}_args){{ {', '.join(fields)} }})"
    return f"{m.cname}({', '.join(['c'] + req)})"


def default_text(d):
    if d is None:
        return None
    try:
        return py2c.ast.literal_eval(d)
    except Exception:
        return py2c.ast.unparse(d)


def main():
    rest, streams, table = [], [], []
    for fname, c, methods in py2c.load_classes(sys.argv[2]):
        for m in methods.values():
            if m.private:
                continue
            line = (f'    if (!strcmp(cls, "{c.name}") && !strcmp(m, "{m.name}"))\n'
                    f"        return {call_expr(m)};")
            (streams if m.stream else rest).append(line)
            table.append({"class": c.name, "method": m.name, "function": m.cname,
                          "stream": m.stream,
                          "params": [{"name": n, "type": t, "required": r,
                                      "default": default_text(d)}
                                     for n, t, d, r in m.params]})
    out = ["/* Generated by tools/gen_calls.py from python-openhab-rest-client – do not edit. */",
           "#include <string.h>",
           '#include "calls.h"', "",
           "static const cJSON* a_(const cJSON* o, const char* n) {",
           "    return cJSON_GetObjectItemCaseSensitive(o, n);", "}",
           "static const char* s_(const cJSON* v) { return cJSON_IsString(v) ? v->valuestring : NULL; }",
           "static int b_(const cJSON* v) { return cJSON_IsTrue(v); }",
           "static openhab_flag f_(const cJSON* v) {",
           "    return cJSON_IsBool(v) ? (cJSON_IsTrue(v) ? OPENHAB_TRUE : OPENHAB_FALSE) : OPENHAB_UNSET;",
           "}",
           "static int i_(const cJSON* v) { return cJSON_IsNumber(v) ? v->valueint : 0; }",
           "static double d_(const cJSON* v) { return cJSON_IsNumber(v) ? v->valuedouble : 0; }",
           "static const cJSON* j_(const cJSON* v) { return cJSON_IsNull(v) ? NULL : v; }", "",
           "cJSON* openhab_call(openhab_client_t* c, const char* cls, const char* m, const cJSON* args) {",
           *rest, "    return NULL;", "}", "",
           "openhab_sse_t* openhab_open_stream(openhab_client_t* c, const char* cls, const char* m,",
           "                                   const cJSON* args) {",
           *streams, "    return NULL;", "}", ""]
    open(sys.argv[3], "w").write("\n".join(out))
    json.dump(table, open(sys.argv[4], "w"), indent=1, ensure_ascii=False)
    print(f"{len(rest)} REST functions, {len(streams)} event streams")


main()
